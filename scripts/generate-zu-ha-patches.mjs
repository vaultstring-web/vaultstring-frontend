function flat(obj, prefix = '', out = {}) {
  for (const [k, v] of Object.entries(obj)) {
    const n = prefix ? `${prefix}.${k}` : k;
    if (v && typeof v === 'object' && !Array.isArray(v)) flat(v, n, out);
    else out[n] = v;
  }
  return out;
}

